-- COD-9 (US-01): accounts. E-mails are stored lower-case; passwords only as BCrypt hashes.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254)             NOT NULL UNIQUE,
    password_hash VARCHAR(100)             NOT NULL,
    full_name     VARCHAR(100)             NOT NULL,
    department    VARCHAR(100),
    bio           VARCHAR(500),
    role          VARCHAR(30)              NOT NULL, -- STUDENT, CLUB_MANAGER, UNIVERSITY_ADMIN, SYSTEM_ADMIN
    status        VARCHAR(30)              NOT NULL, -- PENDING_VERIFICATION, ACTIVE, DISABLED
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
