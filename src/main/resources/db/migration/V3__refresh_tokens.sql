-- COD-11 (US-03): refresh tokens, so sessions can be ended (log-out on every device) while access
-- tokens stay stateless JWTs. Only a SHA-256 hash of each token is stored. Used tokens are kept
-- (used = TRUE) until they expire, so a replayed old token can be detected.
CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64)              NOT NULL UNIQUE,
    user_id    BIGINT                   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used       BOOLEAN                  NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX refresh_tokens_user_idx ON refresh_tokens (user_id);
