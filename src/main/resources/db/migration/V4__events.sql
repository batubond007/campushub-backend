-- COD-118: campus events. Times are instants (TIMESTAMP WITH TIME ZONE): the API sends and receives
-- ISO-8601 UTC ("...Z"), so the server's own time zone never shifts them.
-- organizer_name is what students see (e.g. "ODTÜ Career Centre"); created_by is the account that created it.
CREATE TABLE events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(120)             NOT NULL,
    description    VARCHAR(2000)            NOT NULL,
    location       VARCHAR(200)             NOT NULL,
    start_time     TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time       TIMESTAMP WITH TIME ZONE NOT NULL,
    organizer_name VARCHAR(100)             NOT NULL,
    official       BOOLEAN                  NOT NULL,
    created_by     BIGINT                   NOT NULL REFERENCES users (id),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT events_end_after_start CHECK (end_time > start_time)
);
-- The list shows events that have not ended yet, soonest first.
CREATE INDEX events_end_time_idx ON events (end_time);
CREATE INDEX events_start_time_idx ON events (start_time);
